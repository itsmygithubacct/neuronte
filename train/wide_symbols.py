def ideo(strokes, x0=3.6, y0=3.6, size=10.8, w=KW):
    """Strokes on a 0..10 square, put at (x0, y0) size units across."""
    out = []
    k = size / 10.0
    for pts in strokes:
        out += L(*[(x0 + x * k, y0 + y * k) for x, y in pts], w=w)
    return out


