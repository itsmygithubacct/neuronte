def d(cp, shapes, note=None):
    if cp in DRAWN:
        raise ValueError(f"U+{cp:04X} drawn twice")
    DRAWN[cp] = shapes
    if note:
        NOTES[cp] = note


def kc(shapes):
    """kilix_chrome2's shapes (tenths of box units) in box units."""
    return move(shapes, s=10, cx=0, cy=0)


def spiral(cx, cy, r0, r1, turns, w=1.6, start=0.0):
    n = int(60 * turns)
    return L(*[(cx + (r0 + (r1 - r0) * i / n) * math.cos(start + 2 * math.pi * turns * i / n),
                cy + (r0 + (r1 - r0) * i / n) * math.sin(start + 2 * math.pi * turns * i / n)) for i in range(n + 1)], w=w)


def spokes(cx, cy, r0, r1, n, w, start=-90.0):
    out = []
    for i in range(n):
        a = math.radians(start + 360.0 * i / n)
        out += L((cx + r0 * math.cos(a), cy + r0 * math.sin(a)), (cx + r1 * math.cos(a), cy + r1 * math.sin(a)), w=w)
    return out


def sun(cx, cy, r, ray0, ray1, n=8, w=1.4):
    return D(cx, cy, r) + spokes(cx, cy, ray0, ray1, n, w)


def leaf(cx, cy, length, width, angle):
    """A pointed leaf: a lens length long about (cx, cy), turned angle degrees from pointing right."""
    pts = []
    for i in range(21):
        t = -1 + 2 * i / 20
        pts.append((length / 2 * t, width / 2 * (1 - t * t)))
    for i in range(1, 20):
        t = 1 - 2 * i / 20
        pts.append((length / 2 * t, -width / 2 * (1 - t * t)))
    a = math.radians(angle)
    return F(*[(cx + x * math.cos(a) - y * math.sin(a), cy + x * math.sin(a) + y * math.cos(a)) for x, y in pts])


def wave(x0, x1, y, amp, n, w=1.6):
    pts = [(x0 + (x1 - x0) * i / (12 * n), y - amp * math.sin(2 * math.pi * i / 12)) for i in range(12 * n + 1)]
    return L(*pts, w=w)


def bowl(y=10.0, w=7.0, h=5.4):
    return S(9, y, w, h, 0, 180) + R(6.4, y + h - 0.6, 11.6, y + h + 0.8)


def steam(xs, y0=7.0, y1=2.0, w=1.1):
    out = []
    for x in xs:
        out += L((x, y0), (x - 0.8, y0 - (y0 - y1) / 3), (x, y0 - 2 * (y0 - y1) / 3), (x - 0.8, y1), w=w)
    return out


