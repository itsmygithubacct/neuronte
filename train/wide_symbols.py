def loops(n, a, b, w=1.6):
    pts = []
    m = 40 * n
    for i in range(m + 1):
        t = -n * math.pi + 2 * n * math.pi * i / m
        pts.append((9 + a * t - b * math.sin(t), 10.0 - b * math.cos(t)))
    return L(*pts, w=w)


