def steam(xs, y0=7.0, y1=2.0, w=1.1):
    out = []
    for x in xs:
        out += L((x, y0), (x - 0.8, y0 - (y0 - y1) / 3), (x, y0 - 2 * (y0 - y1) / 3), (x - 0.8, y1), w=w)
    return out


