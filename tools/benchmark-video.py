#!/usr/bin/env python3
"""Reproducible original synthetic video, search timings and comparison clip."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import time
import numpy as np
from neuronte_video import TwoInk,MultiInk,exactness,ROOT


def frames(count,width=160,height=96,seed=20261111):
    # Original procedural footage: gradients, checkerboard, moving shapes,
    # sharp colour boundaries, and deterministic noise; no external artwork.
    rng=np.random.default_rng(seed)
    noise=rng.integers(0,24,(height,width,3))
    y,x=np.mgrid[:height,:width]
    for t in range(count):
        a=np.stack([(x*255//width+t*7)%256,(y*255//height+t*3)%256,((x+y)*2+t*5)%256],-1)
        a=np.clip(a+noise,0,255)
        disk=(x-(t*5%(width+30)-15))**2+(y-height*.45)**2<15**2
        a[disk]=[242,35,104]
        checker=((x//5+y//5+t//3)%2).astype(bool)&(y>height*2//3)
        a[checker]=[12,230,145]
        a[(x>width*.7)&(x<width*.85)&(y<height*.35)]=[253,235,16]
        yield a.astype(np.uint8)


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('output',type=Path);p.add_argument('--frames',type=int,default=30)
    a=p.parse_args();a.output.mkdir(parents=True,exist_ok=True)
    results={'source':'original procedural patterns generated by tools/benchmark-video.py','script_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),'timings':[]}
    sample=next(frames(1,640,384))
    for mode in ['portable','full']:
        begin=time.perf_counter();renderer=TwoInk(mode); setup=time.perf_counter()-begin
        times=[]
        for _ in range(3):
            begin=time.perf_counter(); cells=renderer.fit(sample); times.append(time.perf_counter()-begin)
        decoded=renderer.decode(cells);mse=float(np.square(decoded.astype(float)-sample).mean())
        results['timings'].append(dict(mode=mode,cell=[8,16],grid=[80,24],candidates=len(renderer.scalars),setup_seconds=setup,search_seconds=times,median_fps=1/float(np.median(times)),psnr_db=10*np.log10(255**2/mse)))
    two=TwoInk('full',8,16)
    multi=[MultiInk(cell_w=w,cell_h=h) for w,h in [(8,16),(4,8),(2,4)]]
    src_path=a.output/'source.mp4';cmp_path=a.output/'comparison.mp4'
    def writer(path,w,h):
        return subprocess.Popen(['ffmpeg','-v','error','-y','-f','rawvideo','-pix_fmt','rgb24','-s',f'{w}x{h}','-r','12','-i','-','-an','-c:v','libx264rgb','-crf','0','-preset','fast',str(path)],stdin=subprocess.PIPE)
    source=writer(src_path,160,96);comparison=writer(cmp_path,800,96)
    squared=np.zeros(4); seconds=np.zeros(4); hashes=hashlib.sha256()
    try:
        for frame in frames(a.frames):
            hashes.update(frame.tobytes());source.stdin.write(frame.tobytes());out=[frame]
            begin=time.perf_counter();out.append(two.decode(two.fit(frame)));seconds[0]+=time.perf_counter()-begin
            for i,renderer in enumerate(multi,1):
                begin=time.perf_counter();out.append(renderer.decode(renderer.encode(frame)));seconds[i]+=time.perf_counter()-begin
            for i,recon in enumerate(out[1:]): squared[i]+=np.square(recon.astype(float)-frame).sum()
            comparison.stdin.write(np.concatenate(out,1).tobytes())
    finally:
        source.stdin.close();comparison.stdin.close()
        if source.wait() or comparison.wait(): raise RuntimeError('ffmpeg failed')
    results.update(frames=a.frames,source_rgb_sha256=hashes.hexdigest(),panels=['source','full two-ink 8x16','multi 8x16','multi 4x8','multi 2x4'],panel_seconds=seconds.tolist(),panel_mse=(squared/(a.frames*160*96*3)).tolist(),exactness=exactness())
    results['artifacts']={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in [src_path,cmp_path]}
    (a.output/'results.json').write_text(json.dumps(results,indent=2)+'\n')
    (a.output/'comparison.html').write_text('<!doctype html><meta charset="utf-8"><title>Neuronte video comparison</title><style>body{background:#181818;color:#eee;font:16px sans-serif}video{width:100%;image-rendering:pixelated}p{max-width:70em}</style><h1>Neuronte video</h1><p>Left to right: source · two-ink 8×16 · multi-ink 8×16 · multi-ink 4×8 · multi-ink 2×4. All frames are original procedural drawings. Playback uses lossless RGB H.264; browser decoding support varies.</p><video controls loop src="comparison.mp4"></video><p>Raw reconstructed multi-ink 2×4 output is checked for byte equality to the source; the two coarser sizes average each subcell.</p>')
    print(json.dumps({k:v for k,v in results.items() if k!='exactness'},indent=2))

if __name__=='__main__': main()
